package com.zer0state.zzthat

import com.zer0state.zzthat.api.MessageKey
import com.zer0state.zzthat.app.res
import org.junit.Assert.assertEquals
import org.junit.Assert.assertTrue
import org.junit.Test
import java.io.File
import javax.xml.parsers.DocumentBuilderFactory

/** The generated catalog is the only source of sentences (FR-042, SC-11). */
class CatalogTest {
    private val src = File(System.getProperty("zz.appSrc"))
    private val strings = File(src, "main/res/values/strings.xml")

    private fun catalogNames(): Set<String> {
        val document = DocumentBuilderFactory.newInstance().newDocumentBuilder().parse(strings)
        val nodes = document.getElementsByTagName("string")
        return (0 until nodes.length).map { nodes.item(it).attributes.getNamedItem("name").nodeValue }.toSet()
    }

    /** The app's string resources are exactly the generated catalog: no sentence is authored in the app. */
    @Test
    fun theAppStringsAreTheGeneratedCatalog() {
        val resourceNames = R.string::class.java.fields.map { it.name }.toSet()
        assertEquals(catalogNames(), resourceNames)
        assertTrue(strings.readText().contains("Generated by scripts/sync-zzthis.sh"))
    }

    /** Every error sentence the API layer names is a catalog key, by the same name. */
    @Test
    fun everyMessageKeyIsACatalogString() {
        for (key in MessageKey.entries) {
            val name = key.key.replace('.', '_')
            assertEquals(key.name, R.string::class.java.getField(name).getInt(null), key.res)
        }
    }

    /**
     * No sentence in app source: every Text, label, and description takes a
     * catalog string, a server value, or a code. The one exception is the
     * verbatim license text, which is read from the bundled files.
     */
    @Test
    fun appSourceWritesNoSentence() {
        val pattern = Regex("""(Text|RoleText|ZZButton|BarAction|contentDescription\s*=|stateDescription\s*=)\(?\s*"([^"$]*[A-Za-z]{2}[^"]*)"""")
        val found = src.walkTopDown()
            .filter { it.isFile && it.extension == "kt" && "/test" !in it.path.removePrefix(src.path) }
            .flatMap { file ->
                file.readLines().mapIndexedNotNull { index, line ->
                    // A code, such as the bare mark zz, is not a sentence.
                    val literal = pattern.find(line)?.groupValues?.get(2) ?: return@mapIndexedNotNull null
                    if (com.zer0state.zzthat.grammar.Grammar.parse(literal) is com.zer0state.zzthat.grammar.ParseResult.Success) null else "${file.name}:${index + 1}"
                }
            }
            .toList()
        assertTrue(found.toString(), found.isEmpty())
    }

    /** Layout files hold no sentences (runtime.md, Localization): the app has no layout files at all. */
    @Test
    fun thereAreNoLayoutFiles() {
        assertTrue(src.walkTopDown().none { it.isDirectory && it.name.startsWith("layout") })
    }
}
